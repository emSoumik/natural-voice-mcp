import { mkdir, readFile, writeFile } from 'node:fs/promises';

const files = [
  'content/SKILL.md',
  'content/references/voice-profile.md',
  'content/references/registers.md',
  'content/references/ai-tells.md',
  'content/references/word-bank.md',
  'content/references/examples.md',
];

const sections = await Promise.all(files.map(async (path) =>
  `===== ${path} =====\n${await readFile(path, 'utf8')}`));
await mkdir('src', { recursive: true });
await writeFile('src/playbook.ts', `// Generated by scripts/generate-playbook.mjs. Do not edit.\nexport const playbook = ${JSON.stringify(sections.join('\n\n'))};\n`);
console.log(`Bundled ${files.length} public voice references.`);
